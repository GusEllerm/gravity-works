/**
 * THE HOUSE (`house`) — one new level id joining the registry APPEND-ONLY
 * (Decision Log 2026-10-12, "THE DOWNHILL greenlit"): the six ratified sets
 * at the CANON deck altitudes, joined by the authored drop-and-catch legs
 * of `src/world/house-frame.ts`, with the whole descent driven as DATA:
 *
 * - the world floor slab is `Level.floor` — one physical collider, the
 *   tunnel law, the spike's departure rule (`World`'s fell line at top−0.05);
 * - the mezzanine release and the wind are `Level.inputs` — THE INPUT LAW
 *   made product: every force that can move the car lives in the replayed
 *   data, step-keyed, so the house run's hash IS its receipt;
 * - the six rooms' thresholds are `Level.parcels` — ROOMS COLLECTED is
 *   physics approvals under the shipped capture law (the read-only probe,
 *   `approveParcels`), never a menu checkbox;
 * - the run's END is honest: `parStatuses` names the ways a downhill run
 *   completes (into the last cup, stopped mid-descent, or gone off the
 *   edge of the world). No cup ends the descent early: the ONLY cup the
 *   outcome law reads is the PORCH's (the last `finishCup` in the build) —
 *   the full house finishes, everything else stops or falls, and the
 *   result line says where: "N rooms · T s — you stopped at the <room>".
 *
 * It is nobody's rung: the campaign stays byte-identical, `replay:all` 30/30
 * is the referee, and the thirty rungs remain the TOURS the greenlight
 * entry demoted them to — reachable from the house page's windows.
 */
import type { Build, PlacedPiece } from '../../track/build.ts';
import type { Level } from '../level.ts';
import { registerLevel } from './feeltrack.level.ts';
import { houseLayout, DESCENT_ORDER } from '../house-frame.ts';

export const HOUSE_ID = 'house';

export interface HouseLevel extends Level {
  /** The house owns its room graph; `set` is deliberately absent — the
   *  single-set mount law of the campaign shells does not apply to a
   *  world with six rooms in it. */
  parcels: NonNullable<Level['parcels']>;
  inputs: NonNullable<Level['inputs']>;
  parBuild(): Build;
}

/** THE reference build: every deck and every leg as one plain-data `Build`
 *  (piece order is deterministic: garage deck, leg, kitchen deck, …, porch
 *  deck — so the PORCH cup is the last capture volume and the only cup the
 *  outcome law can read; `tests/unit/house-levels.test.ts` pins it). */
function parBuild(): Build {
  const l = houseLayout();
  const pieces: PlacedPiece[] = [];
  let seq = 0;
  l.decks.forEach((deck, i) => {
    for (const p of deck.build.pieces) pieces.push({ ...p, seq: seq++ });
    const leg = l.legs[i];
    if (leg) for (const p of leg.build.pieces) pieces.push({ ...p, seq: seq++ });
  });
  return { levelId: HOUSE_ID, pieces, seed: 0 };
}

export const HOUSE: HouseLevel = (() => {
  const l = houseLayout();
  const build = parBuild();
  const def = {
      id: HOUSE_ID,
      name: 'The House',
      seed: 0,
      startSocket: l.start,
      budget: build.pieces.length,
      par: { pieces: build.pieces.length, time: 0 }, // par.time regenerated by `npm run pars`
      maxTime: 12,
      placeholderBuild: parBuild,
      parBuild,
      floor: l.floor,
      inputs: { windEvery: 60, windDeltaV: 1.2, governor: 2.5, launchSpeed: 0.4 },
      parcels: l.parcels.map((p) => ({ room: p.room, center: p.center, radius: p.radius })),
      parStatuses: ['finished', 'stalled', 'fell'],
    } satisfies HouseLevel;
    registerLevel(def);
    return def;
})();

/** The descent order, re-exported for the surfaces that print it. */
export { DESCENT_ORDER };
