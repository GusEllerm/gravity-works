/**
 * THE BLOCKED-RIM RUNG (P4 shortlist item 1 — the 2026-10-10 player
 * evaluation's UNFIXED item: "kitchen02 — the dump STILL finishes (union of
 * both lines, every order) … the 'choice' is still a formality").
 *
 * kitchen02 declares `blockedGoalSeat`: the cup's own body refuses any seat
 * across its mouth (`goalGuardFor` in `src/ui/builder.ts`), and by the
 * level's own reach-sum law the whole-tray union's 4th ask lands there in
 * EVERY order. In-game the union dump is no longer a build — the last piece
 * is refused where the dump aims it (the chain head), and the trio the dump
 * left seated falls in the void. The two AUTHORED lines (3 of 4 pieces)
 * seat and finish exactly as the level file says.
 */
import { test, expect, type Page } from '@playwright/test'
import { goto } from './goto.ts'

// The `ready`/finish waits below document 60 s; the default 30 s TEST timeout
// silently cuts that intent (the garage-era CI reds, `campaign.spec.ts` header).
// Measured wall clocks under contention: 22–24 s for the two-boots/two-launches
// test on a SwiftShader-saturated 18-core box (CPU-starved sweep) and 30.4 s
// (test timeout) on a saturated CI runner — the 2026-10-10 08:51Z red. `slow()`
// carries the budget the waits already promise; the event waits stay untouched.
test.slow()

const ready = (page: Page) =>
  expect(page.locator('#gw-status')).toContainText('ready', { timeout: 60_000 })

const place = (page: Page) => page.click('#gw-place')

test.describe('kitchen02: the union dump cannot be built (P4 item 1)', () => {
  test('the dump seats three and the fourth ask is refused — naming the cup', async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', (err) => errors.push(String(err)))
    await goto(page, '/?level=kitchen02')
    await ready(page)

    // the tray dump: hold each piece, press Place, let the ring walk the
    // chain — straight, straight, gapLip seat exactly as they always did…
    for (const kind of ['straight', 'straight', 'gapLip']) {
      await page.click(`#gw-tray-${kind}`)
      await place(page)
    }
    await expect(page.locator('#gw-piece-count')).toHaveText('3 of 4 pieces used')

    // …and the fourth ask of the union dies at the rim, WHEREVER the order:
    // the drop's tail deck reaches INTO the cup, the refusal names the cup
    // and points at the verb table's own walk key.
    await page.click('#gw-tray-drop')
    await place(page)
    await expect(page.locator('#gw-ghost-state')).toHaveText(
      'blocked — the cup is in the way · press ] to walk the open ends',
    )
    await expect(page.locator('#gw-piece-count')).toHaveText('3 of 4 pieces used')
    expect(errors).toEqual([])
  })

  test('the trio the dump left seated FALLS — the union line can die', async ({ page }) => {
    await goto(page, '/?level=kitchen02')
    await ready(page)
    for (const kind of ['straight', 'straight', 'gapLip']) {
      await page.click(`#gw-tray-${kind}`)
      await place(page)
    }
    await page.click('#gw-launch')
    await expect(page.locator('#gw-status')).toContainText('fell off', { timeout: 60_000 })
  })

  // ---- round-2 Lane A (the 2026-10-11 player evaluation, k02 orders 1–4) ----
  //
  // The four stranger click orders the evaluation replayed at human pacing
  // are asserted here as a SAMPLED SET of the full permutation table
  // (generated by `scripts/k02-order-table.mjs`, swept exhaustively in
  // `tests/unit/goal-guard.test.ts`): no order seats four pieces; the
  // evaluation's order 2 (run-out seat) is REFUSED at the mouth with the
  // run-ends truth, its order 3 (off-list trio) pays two stars and never
  // three, and the only order that pays three is the reference seating
  // itself (drop first, the lip left on the tray).
  const fresh = async (page: Page) => {
    await page.addInitScript(() => {
      for (const k of Object.keys(localStorage)) if (k.startsWith('gravity-works.')) localStorage.removeItem(k)
    })
    await goto(page, '/?level=kitchen02')
    await ready(page)
  }
  const clickOrder = async (page: Page, kinds: string[]) => {
    for (const kind of kinds) {
      await page.click(`#gw-tray-${kind}`)
      await place(page)
    }
  }

  test("order s,s,d,lip: the 4th ask aimed PAST the cup is refused at the mouth, and the seated trio finishes for two — never the evaluation's under-par two-star build", async ({ page }) => {
    await fresh(page)
    await clickOrder(page, ['straight', 'straight', 'drop', 'gapLip'])
    // the ring auto-followed the chain head THROUGH the cup onto the run-out
    // end — the seat the evaluation's order 2 built. It is refused now.
    await expect(page.locator('#gw-ghost-state')).toContainText(
      'blocked — the run ends at the cup, so nothing past it is ever built',
    )
    await expect(page.locator('#gw-piece-count')).toHaveText('3 of 4 pieces used')
    await page.click('#gw-launch')
    await expect(page.locator('#gw-status')).toContainText('finished', { timeout: 60_000 })
    await expect(page.locator('#gw-result-stars')).toHaveText('★★☆')
    await expect(page.locator('#gw-result-pieces')).toContainText('3 pieces')
  })

  test("order d,l,s,s: the off-list trio pays the clock, not the star — the evaluation's order 3 reproduction", async ({ page }) => {
    await fresh(page)
    await clickOrder(page, ['drop', 'gapLip', 'straight', 'straight'])
    // the 4th straight is refused at the rim (the body guard, as advertised)
    await expect(page.locator('#gw-ghost-state')).toContainText('blocked — the cup is in the way')
    await page.click('#gw-launch')
    await expect(page.locator('#gw-status')).toContainText('finished', { timeout: 60_000 })
    await expect(page.locator('#gw-result-stars')).toHaveText('★★☆') // was ★★★ at the 1.05 par
  })

  test('blind clear: the reference seating drop, straight, straight finishes at or under the 1.00 par for three stars', async ({ page }) => {
    await fresh(page)
    await clickOrder(page, ['drop', 'straight', 'straight'])
    await expect(page.locator('#gw-piece-count')).toHaveText('3 of 4 pieces used')
    await page.click('#gw-launch')
    await expect(page.locator('#gw-status')).toContainText('finished', { timeout: 60_000 })
    await expect(page.locator('#gw-result-stars')).toHaveText('★★★')
  })

  test('a guarded rung REFUSES every seat past the goal, not just the goal’s own', async ({ page }) => {
    await goto(page, '/?level=kitchen02')
    await ready(page)
    await page.click('#gw-tray-straight')
    await page.locator('#gw-builder').press('ArrowRight') // past the rim: the fixture run-out's open end
    await expect(page.locator('#gw-ghost-state')).toContainText(
      'blocked — the run ends at the cup, so nothing past it is ever built',
    )
    const before = await page.textContent('#gw-piece-count')
    await place(page)
    await expect(page.locator('#gw-piece-count')).toHaveText(String(before))
  })

  test('both authored lines still seat everything and finish', async ({ page }) => {
    // Start each line from an EMPTY board: a same-rung revisit RELOADS the
    // autosaved working build (playtest S's honest reload), which would
    // hand the arc a spent drop. The save keys go away BEFORE every
    // document load of this test (an evaluate-after-navigation would be
    // too late, and about:blank denies localStorage access).
    await page.addInitScript(() => {
      for (const k of Object.keys(localStorage)) if (k.startsWith('gravity-works.')) localStorage.removeItem(k)
    })
    for (const line of [
      ['straight', 'drop', 'straight'], // the lazy par
      ['gapLip', 'drop', 'straight'], // the arc
    ]) {
      await goto(page, '/?level=kitchen02')
      await ready(page)
      for (const kind of line) {
        await page.click(`#gw-tray-${kind}`)
        await place(page)
      }
      await expect(page.locator('#gw-piece-count')).toHaveText('3 of 4 pieces used')
      await page.click('#gw-launch')
      await expect(page.locator('#gw-status')).toContainText('finished', { timeout: 60_000 })
    }
  })

})
